export const CUSTOM_SECTION = "CUSTOM";

const INDEX = {};
Object.values(STEEL_SERIES).forEach((list) =>
  list.forEach((s) => {
    INDEX[s.name] = s;
  }),
);

export function findSection(name) {
  return INDEX[name] || null;
}

/** [{ series: "MB", items: [...] }, ...] for one category key */
export function sectionsInCategory(categoryKey) {
  const cat = STEEL_CATEGORIES.find((c) => c.key === categoryKey);
  if (!cat) return [];
  return cat.series.map((series) => ({ series, items: STEEL_SERIES[series] }));
}

export function sectionLabel(s) {
  return `${s.name} - ${s.kgm} kg/m`;
}
